# 自定义聚合函数
def calculate_range(x):
    return x.max() - x.min()


# 使用自定义函数聚合
df.groupby('季度')['价格'].agg({
'平均价格': 'mean',
'价格范围': calculate_range,
'最高价格': lambda x: x[x > x.mean()].max()
})
# 使用字典指定不同列的聚合函数
aggregation_dict = {
'价格': ['mean', 'std'],
'销量': ['sum', 'count'],
'折扣': lambda x: x[x > 0.9].mean()
}
grouped_df = df.groupby('季度').agg(aggregation_dict)


# GroupBy高级参数
